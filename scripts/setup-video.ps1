# One-time Windows x64 development setup. Does not install system tools.
$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$depsRoot = Join-Path $repoRoot '.deps'
$downloads = Join-Path $depsRoot 'downloads'
New-Item -ItemType Directory -Force $downloads | Out-Null

function Get-VerifiedFile($Url, $Path, $Sha256) {
    if (!(Test-Path -LiteralPath $Path) -or (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash -ne $Sha256) {
        Invoke-WebRequest -Uri $Url -OutFile $Path
    }
    if ((Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash -ne $Sha256) { throw "Checksum mismatch: $Path" }
}

Add-Type -AssemblyName System.IO.Compression.FileSystem
$ffmpegZip = Join-Path $downloads 'ffmpeg.zip'
Get-VerifiedFile 'https://github.com/BtbN/FFmpeg-Builds/releases/download/autobuild-2026-10-22-13-06/ffmpeg-n9.0.2-33-g4cf298e66a-win64-lgpl-shared-9.0.zip' $ffmpegZip '14d2da681ed1999a6232de61f99d869a46df437dd910d69c1fb5c9c83172242e'
$ffmpegRoot = Join-Path $depsRoot 'ffmpeg'
New-Item -ItemType Directory -Force $ffmpegRoot | Out-Null
$archive = [IO.Compression.ZipFile]::OpenRead($ffmpegZip)
try {
    foreach ($entry in $archive.Entries) {
        $relative = ($entry.FullName -split '/', 2)[1]
        if (!$relative -or $relative.EndsWith('/')) { continue }
        if ($relative -notmatch '^(include/|lib/|bin/.*\.dll$|LICENSE|COPYING|README)') { continue }
        $target = [IO.Path]::GetFullPath((Join-Path $ffmpegRoot $relative))
        if (!$target.StartsWith($ffmpegRoot + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) { throw 'Invalid archive path' }
        New-Item -ItemType Directory -Force (Split-Path -Parent $target) | Out-Null
        [IO.Compression.ZipFileExtensions]::ExtractToFile($entry, $target, $true)
    }
} finally { $archive.Dispose() }

$clangZip = Join-Path $downloads 'libclang.whl'
Get-VerifiedFile 'https://files.pythonhosted.org/packages/0b/2d/3f480b1e1d31eb3d6de5e3ef641954e5c67430d5ac93b7fa7e07589576c7/libclang-18.1.1-py2.py3-none-win_amd64.whl' $clangZip '4dd2d3b82fab35e2bf9ca717d7b63ac990a3519c7e312f19fa8e86dcc712f7fb'
$clangRoot = Join-Path $depsRoot 'libclang'
New-Item -ItemType Directory -Force $clangRoot | Out-Null
$archive = [IO.Compression.ZipFile]::OpenRead($clangZip)
try {
    $entry = $archive.GetEntry('libclang-18.1.1.data/platlib/clang/native/libclang.dll')
    if (!$entry) { throw 'libclang.dll is missing from the package' }
    [IO.Compression.ZipFileExtensions]::ExtractToFile($entry, (Join-Path $clangRoot 'libclang.dll'), $true)
} finally { $archive.Dispose() }

$configRoot = Join-Path $repoRoot '.cargo'
$configPath = Join-Path $configRoot 'config.toml'
$config = @'
# Generated by scripts/setup-video.ps1; paths are relative to the repository root.
[env]
FFMPEG_DIR = { value = ".deps/ffmpeg", relative = true }
LIBCLANG_PATH = { value = ".deps/libclang", relative = true }
'@
if ((Test-Path -LiteralPath $configPath) -and (Get-Content -LiteralPath $configPath -Raw).Trim() -ne $config.Trim()) {
    throw 'Existing .cargo/config.toml was preserved. Add FFMPEG_DIR and LIBCLANG_PATH to its [env] table manually.'
}
New-Item -ItemType Directory -Force $configRoot | Out-Null
Set-Content -LiteralPath $configPath -Value $config -Encoding utf8
Write-Host 'Native video dependencies ready. cargo build/test/run now work without ffmpeg.exe.'
